-- PawCare / PostgreSQL 15+. All timestamptz values are instants in UTC.
-- All people share one database, but private customer data is scoped by owner_id.
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  phone VARCHAR(25), address VARCHAR(255),
  role VARCHAR(16) NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'staff', 'admin')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);

CREATE TABLE IF NOT EXISTS staff_profiles (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  specialty VARCHAR(160), bio VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS pets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  species VARCHAR(16) NOT NULL CHECK (species IN ('dog','cat','other')),
  breed VARCHAR(120), gender VARCHAR(16) NOT NULL DEFAULT 'unknown' CHECK (gender IN ('male','female','unknown')),
  birthday DATE, weight_kg NUMERIC(6,2) CHECK (weight_kg > 0),
  color VARCHAR(80), notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pets_owner ON pets(owner_id);
CREATE TABLE IF NOT EXISTS care_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pets(id) ON DELETE CASCADE,
  title VARCHAR(160) NOT NULL,
  record_type VARCHAR(16) NOT NULL DEFAULT 'other' CHECK (record_type IN ('vaccination','medical','grooming','other')),
  care_date DATE NOT NULL, description TEXT, next_due_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_care_pet_date ON care_records(pet_id, care_date);

CREATE TABLE IF NOT EXISTS services (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE, category VARCHAR(80) NOT NULL DEFAULT 'Chăm sóc',
  description TEXT, duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES users(id),
  pet_id INTEGER NOT NULL REFERENCES pets(id),
  service_id INTEGER NOT NULL REFERENCES services(id),
  staff_id INTEGER REFERENCES users(id),
  starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','confirmed','in_progress','completed','cancelled')),
  price_snapshot NUMERIC(12,2) NOT NULL CHECK (price_snapshot >= 0),
  notes VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT appointment_positive_duration CHECK (ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS idx_appointments_customer ON appointments(customer_id, starts_at);
CREATE INDEX IF NOT EXISTS idx_appointments_staff ON appointments(staff_id, starts_at, ends_at);
CREATE INDEX IF NOT EXISTS idx_appointments_status ON appointments(status);

CREATE OR REPLACE FUNCTION pawcare_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END $$;
DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION pawcare_touch_updated_at();
DROP TRIGGER IF EXISTS trg_pets_updated_at ON pets;
CREATE TRIGGER trg_pets_updated_at BEFORE UPDATE ON pets FOR EACH ROW EXECUTE FUNCTION pawcare_touch_updated_at();
DROP TRIGGER IF EXISTS trg_services_updated_at ON services;
CREATE TRIGGER trg_services_updated_at BEFORE UPDATE ON services FOR EACH ROW EXECUTE FUNCTION pawcare_touch_updated_at();
DROP TRIGGER IF EXISTS trg_appointments_updated_at ON appointments;
CREATE TRIGGER trg_appointments_updated_at BEFORE UPDATE ON appointments FOR EACH ROW EXECUTE FUNCTION pawcare_touch_updated_at();

-- Backward-compatible upgrade from the previous shared PostgreSQL release.
-- Roles in users are retained for migration history. Session role is resolved
-- from organization_members, except globally scoped platform Owner.
CREATE TABLE organizations (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 slug VARCHAR(100) NOT NULL UNIQUE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE organization_members (
 organization_id INTEGER NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role VARCHAR(12) NOT NULL CHECK(role IN ('admin','staff')),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(organization_id,user_id)
);
CREATE INDEX idx_members_user ON organization_members(user_id,organization_id);
CREATE TABLE invitations (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 email VARCHAR(190) NOT NULL,
 role VARCHAR(12) NOT NULL CHECK(role IN ('admin','staff')),
 token_hash CHAR(64) NOT NULL UNIQUE,
 created_by INTEGER NOT NULL REFERENCES users(id),
 expires_at TIMESTAMPTZ NOT NULL,
 accepted_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_invitations_org ON invitations(organization_id);
CREATE TABLE role_audit_logs (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 actor_id INTEGER NOT NULL REFERENCES users(id),
 organization_id INTEGER REFERENCES organizations(id),
 target_user_id INTEGER REFERENCES users(id),
 action VARCHAR(80) NOT NULL,
 details JSONB NOT NULL DEFAULT '{}'::jsonb,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

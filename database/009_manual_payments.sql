-- 009_manual_payments.sql
-- Cash at store + manually reconciled bank transfers. No payment gateway capture.
-- The amount comes exclusively from the immutable appointment price snapshot.
CREATE TABLE IF NOT EXISTS payments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
 appointment_id INTEGER NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
 customer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 amount NUMERIC(12,2) NOT NULL CHECK(amount >= 0),
 currency VARCHAR(3) NOT NULL DEFAULT 'VND' CHECK(currency='VND'),
 method VARCHAR(20) NOT NULL DEFAULT 'cash' CHECK(method IN ('cash','bank_transfer')),
 status VARCHAR(24) NOT NULL DEFAULT 'unpaid'
   CHECK(status IN ('unpaid','pending_review','paid','refund_required','refunded','void')),
 payment_reference VARCHAR(32) NOT NULL UNIQUE,
 customer_note VARCHAR(300),
 admin_note VARCHAR(500),
 paid_at TIMESTAMPTZ,
 reviewed_at TIMESTAMPTZ,
 reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_payments_org_status ON payments(organization_id,status,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_payments_customer ON payments(customer_id,created_at DESC);
DROP TRIGGER IF EXISTS trg_payments_updated_at ON payments;
CREATE TRIGGER trg_payments_updated_at BEFORE UPDATE ON payments
 FOR EACH ROW EXECUTE FUNCTION pawcare_touch_updated_at();
-- Backfill historical appointments as UNPAID; never invent that prior money was received.
INSERT INTO payments(organization_id,appointment_id,customer_id,amount,method,status,payment_reference)
 SELECT a.organization_id,a.id,a.customer_id,a.price_snapshot,'cash',
 CASE WHEN a.status='cancelled' THEN 'void' ELSE 'unpaid' END,
 'PC'||lpad(a.id::text,8,'0')
 FROM appointments a
 ON CONFLICT (appointment_id) DO NOTHING;
